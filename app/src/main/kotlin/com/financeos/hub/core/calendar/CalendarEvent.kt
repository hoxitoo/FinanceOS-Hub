package com.financeos.hub.core.calendar

import java.time.LocalDate

/**
 * Одно событие календаря: что-то, что случится в известную дату.
 *
 * Календарь СВОДИТ события из разных источников, а не хранит их в одной таблице. Это ключевое
 * решение: приложение уже вычисляет даты в трёх местах — платёж по кредитке, следующее списание
 * подписки, срок цели, — и переносить их в общую таблицу значило бы дублировать данные и разводить
 * рассинхрон. Источник остаётся хозяином своих дат, календарь только собирает.
 *
 * Отсюда же ответ на вопрос «куда потом встанут инвестиции»: они добавят СВОЙ вид события
 * ([EventKind.INVESTMENT]) и свою функцию, которая его порождает. Ни модель, ни экран, ни расчёт
 * «Свободно» при этом не меняются.
 */
data class CalendarEvent(
    /** Стабильный в пределах пересчёта ключ: `вид:идентификатор:дата`. Нужен для `key` в списках. */
    val id: String,
    val date: LocalDate,
    val title: String,
    /** Модуль суммы. Направление живёт в [direction], чтобы знак нигде не потерялся. */
    val amountKopecks: Long,
    val currency: String,
    val direction: EventDirection,
    val kind: EventKind,
    val confidence: EventConfidence,

    /**
     * Двигает ли это событие деньги.
     *
     * `false` у сроков и напоминаний. Самый важный случай — конец беспроцентного периода по
     * кредитке: это ДЕДЛАЙН, а не платёж, и вычитать его из «Свободно» нельзя, иначе одна и та же
     * задолженность уменьшит свободные деньги дважды — как долг и как «предстоящий платёж».
     *
     * У инвестиций будет ровно то же разделение: купон прибавляет, плановый взнос вычитает, а
     * напоминание о ребалансировке не делает ни того ни другого.
     */
    val affectsFree: Boolean,

    /** Счёт, с которого ждём движение. `null` — любой. */
    val accountId: String? = null,
    val categoryId: String? = null,
    /** Ссылка на первоисточник: id обязательства, счёта, цели. Для перехода по тапу. */
    val sourceId: String? = null,
    /** Уже закрыто найденной операцией. Из «Свободно» такое событие выпадает. */
    val settled: Boolean = false,
)

enum class EventDirection { OUT, IN }

/**
 * Откуда событие взялось. Определяет иконку, подпись и то, можно ли назвать его просроченным.
 *
 * Порядок объявления — порядок «важности» при совпадении дат: платёж банку идёт выше подписки,
 * подписка выше срока цели.
 */
enum class EventKind {
    /** Платёж по кредитной карте. Самое надёжное, что есть: сумму и дату прислал банк. */
    CREDIT_DUE,
    /** Конец беспроцентного периода. СРОК, не платёж — [CalendarEvent.affectsFree] = false. */
    CREDIT_GRACE,
    /** Объявленное вами обязательство: аренда, налог, разовый платёж. */
    PLANNED,
    /** Следующее списание найденной подписки. Оценка. */
    SUBSCRIPTION,
    /** Срок цели. Тоже не платёж — деньги никуда не уходят, просто наступает дата. */
    GOAL,
    /** Задел на будущее: купон, дивиденд, плановый взнос в портфель. */
    INVESTMENT,
}

/**
 * Насколько можно верить сумме и дате. Пользователь имеет право знать это до того, как примет
 * решение, и приложение обязано различать источники, а не сваливать их в одну кучу.
 *
 * Тот же принцип уже действует на экране кредитки (`PaymentSource.BANK` против `INFERRED`).
 */
enum class EventConfidence {
    /** Банк прислал сумму и дату. */
    BANK,
    /** Вы их указали. */
    DECLARED,
    /** Приложение вывело из истории. Может ошибаться. */
    INFERRED,
}
